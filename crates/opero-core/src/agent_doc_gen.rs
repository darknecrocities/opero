use chrono::Utc;
use std::io::Write;
use std::path::{Path, PathBuf};
use zip::write::SimpleFileOptions;
use zip::ZipWriter;

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

fn pdf_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '(' => out.push_str("\\("),
            ')' => out.push_str("\\)"),
            '\\' => out.push_str("\\\\"),
            c if c.is_ascii() && !c.is_ascii_control() => out.push(c),
            _ => out.push(' '),
        }
    }
    out
}

fn slugify(title: &str) -> String {
    let mut slug: String = title
        .to_lowercase()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
        .collect();
    while slug.contains("--") {
        slug = slug.replace("--", "-");
    }
    let clean = slug.trim_matches('-').chars().take(42).collect::<String>();
    if clean.is_empty() { "opero-document".into() } else { clean }
}

fn build_default_sections(title: &str, topic: &str) -> Vec<(String, String)> {
    vec![
        ("Overview".into(), format!("Prepared locally by OPERO Pero Agent for: {title}.")),
        ("Scope & Context".into(), format!("Request summary: {topic}")),
        ("Key Action Items".into(), "1. Review generated content and verify details.\n2. Assign owners and target dates.\n3. Share approved version with stakeholders.".into()),
        ("Status".into(), format!("Generated offline on {} (Zero cloud API required).", Utc::now().format("%Y-%m-%d %H:%M UTC"))),
    ]
}

fn write_pdf(path: &Path, title: &str, sections: &[(String, String)]) -> Result<(), String> {
    let mut lines: Vec<String> = vec![title.to_string(), format!("Generated by OPERO · {}", Utc::now().format("%Y-%m-%d")), String::new()];
    for (h, body) in sections {
        lines.push(h.clone());
        for raw in body.lines() {
            let mut cur = String::new();
            for w in raw.split_whitespace() {
                if cur.len() + w.len() + 1 > 78 {
                    lines.push(cur);
                    cur = w.to_string();
                } else {
                    if !cur.is_empty() { cur.push(' '); }
                    cur.push_str(w);
                }
            }
            if !cur.is_empty() { lines.push(cur); }
        }
        lines.push(String::new());
    }

    let mut stream = String::from("BT\n/F1 16 Tf\n54 756 Td\n");
    for (idx, line) in lines.iter().take(42).enumerate() {
        if idx == 1 {
            stream.push_str("/F1 10 Tf\n0 -20 Td\n");
        } else if idx > 1 {
            stream.push_str("0 -15 Td\n");
        }
        stream.push_str(&format!("({}) Tj\n", pdf_escape(line)));
    }
    stream.push_str("ET\n");

    let mut pdf = Vec::new();
    let mut offsets = Vec::new();
    pdf.extend_from_slice(b"%PDF-1.4\n");
    let objs = [
        "1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n".to_string(),
        "2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj\n".to_string(),
        "3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >> endobj\n".to_string(),
        "4 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj\n".to_string(),
        format!("5 0 obj << /Length {} >> stream\n{}endstream endobj\n", stream.len(), stream),
    ];
    for o in &objs {
        offsets.push(pdf.len());
        pdf.extend_from_slice(o.as_bytes());
    }
    let xref_pos = pdf.len();
    pdf.extend_from_slice(format!("xref\n0 {}\n0000000000 65535 f \n", objs.len() + 1).as_bytes());
    for off in offsets {
        pdf.extend_from_slice(format!("{off:010} 00000 n \n").as_bytes());
    }
    pdf.extend_from_slice(
        format!("trailer << /Size {} /Root 1 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n", objs.len() + 1).as_bytes(),
    );
    std::fs::write(path, pdf).map_err(|e| e.to_string())
}

fn write_docx(path: &Path, title: &str, sections: &[(String, String)]) -> Result<(), String> {
    let file = std::fs::File::create(path).map_err(|e| e.to_string())?;
    let mut zip = ZipWriter::new(file);
    let opts = SimpleFileOptions::default();

    let mut body = format!(
        "<w:p><w:pPr><w:pStyle w:val=\"Title\"/></w:pPr><w:r><w:rPr><w:b/><w:sz w:val=\"36\"/></w:rPr><w:t>{}</w:t></w:r></w:p>",
        xml_escape(title)
    );
    for (h, text) in sections {
        body.push_str(&format!(
            "<w:p><w:r><w:rPr><w:b/><w:sz w:val=\"26\"/></w:rPr><w:t>{}</w:t></w:r></w:p>",
            xml_escape(h)
        ));
        for line in text.lines() {
            body.push_str(&format!("<w:p><w:r><w:t>{}</w:t></w:r></w:p>", xml_escape(line)));
        }
    }

    let entries = [
        ("[Content_Types].xml", r#"<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>"#.to_string()),
        ("_rels/.rels", r#"<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>"#.to_string()),
        ("word/document.xml", format!(r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>{body}</w:body></w:document>"#)),
    ];
    for (name, content) in entries {
        zip.start_file(name, opts).map_err(|e| e.to_string())?;
        zip.write_all(content.as_bytes()).map_err(|e| e.to_string())?;
    }
    zip.finish().map_err(|e| e.to_string())?;
    Ok(())
}

fn write_xlsx(path: &Path, title: &str, sections: &[(String, String)]) -> Result<(), String> {
    let file = std::fs::File::create(path).map_err(|e| e.to_string())?;
    let mut zip = ZipWriter::new(file);
    let opts = SimpleFileOptions::default();

    let mut rows: Vec<(String, String, String)> = vec![
        ("Section".into(), "Details".into(), "Status".into()),
        ("Document Title".into(), title.to_string(), "Ready".into()),
    ];
    for (h, text) in sections {
        for (i, line) in text.lines().enumerate() {
            rows.push((if i == 0 { h.clone() } else { String::new() }, line.trim().to_string(), "Active".into()));
        }
    }

    let mut sheet_rows = String::new();
    for (idx, (c1, c2, c3)) in rows.iter().enumerate() {
        let r = idx + 1;
        sheet_rows.push_str(&format!(
            "<row r=\"{r}\"><c r=\"A{r}\" t=\"inlineStr\"><is><t>{}</t></is></c><c r=\"B{r}\" t=\"inlineStr\"><is><t>{}</t></is></c><c r=\"C{r}\" t=\"inlineStr\"><is><t>{}</t></is></c></row>",
            xml_escape(c1), xml_escape(c2), xml_escape(c3)
        ));
    }

    let entries = [
        ("[Content_Types].xml", r#"<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>"#.to_string()),
        ("_rels/.rels", r#"<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>"#.to_string()),
        ("xl/workbook.xml", r#"<?xml version="1.0" encoding="UTF-8"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="OPERO Sheet" sheetId="1" r:id="rId1"/></sheets></workbook>"#.to_string()),
        ("xl/_rels/workbook.xml.rels", r#"<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/></Relationships>"#.to_string()),
        ("xl/worksheets/sheet1.xml", format!(r#"<?xml version="1.0" encoding="UTF-8"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>{sheet_rows}</sheetData></worksheet>"#)),
    ];
    for (name, content) in entries {
        zip.start_file(name, opts).map_err(|e| e.to_string())?;
        zip.write_all(content.as_bytes()).map_err(|e| e.to_string())?;
    }
    zip.finish().map_err(|e| e.to_string())?;
    Ok(())
}

pub fn generate_agent_document(
    data_dir: &Path,
    action_id: &str,
    format: &str,
    title: &str,
    topic: &str,
) -> Result<(PathBuf, usize), String> {
    let out_dir = data_dir.join("exports");
    std::fs::create_dir_all(&out_dir).map_err(|e| e.to_string())?;
    let ext = match format.to_lowercase().as_str() {
        "pdf" => "pdf",
        "docx" | "word" | "doc" => "docx",
        "xlsx" | "excel" | "xls" => "xlsx",
        "csv" => "csv",
        "html" => "html",
        _ => "md",
    };
    let short_id: String = action_id.chars().take(12).collect();
    let path = out_dir.join(format!("{}-{short_id}.{ext}", slugify(title)));
    let sections = build_default_sections(title, topic);

    match ext {
        "pdf" => write_pdf(&path, title, &sections)?,
        "docx" => write_docx(&path, title, &sections)?,
        "xlsx" => write_xlsx(&path, title, &sections)?,
        "csv" => {
            let mut csv = String::from("\u{FEFF}Section,Details,Status\n");
            for (h, b) in &sections {
                let clean = b.replace('"', "\"\"").replace('\n', " | ");
                csv.push_str(&format!("\"{}\",\"{}\",\"Ready\"\n", h.replace('"', "\"\""), clean));
            }
            std::fs::write(&path, csv).map_err(|e| e.to_string())?;
        }
        "html" => {
            let mut body = format!("<h1>{}</h1>", xml_escape(title));
            for (h, b) in &sections {
                body.push_str(&format!("<h2>{}</h2><p>{}</p>", xml_escape(h), xml_escape(b).replace('\n', "<br/>")));
            }
            let html = format!("<!doctype html><html><head><meta charset=\"utf-8\"/><title>{}</title><style>body{{font-family:-apple-system,sans-serif;max-width:740px;margin:40px auto;padding:0 20px;background:#FAF9F7;color:#0F172A;line-height:1.6;}}</style></head><body>{body}</body></html>", xml_escape(title));
            std::fs::write(&path, html).map_err(|e| e.to_string())?;
        }
        _ => {
            let mut md = format!("# {title}\n\n");
            for (h, b) in &sections {
                md.push_str(&format!("## {h}\n\n{b}\n\n"));
            }
            std::fs::write(&path, md).map_err(|e| e.to_string())?;
        }
    }

    let bytes = std::fs::metadata(&path).map(|m| m.len() as usize).unwrap_or(0);
    Ok((path, bytes))
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    #[test]
    fn test_generate_pdf_docx_xlsx_and_csv_offline() {
        let dir = tempdir().unwrap();
        let (pdf, sz_p) = generate_agent_document(dir.path(), "act_p1", "pdf", "MMI Onboarding", "Checklist").unwrap();
        assert!(sz_p > 100 && std::fs::read(&pdf).unwrap().starts_with(b"%PDF-1.4"));

        let (docx, sz_d) = generate_agent_document(dir.path(), "act_d1", "docx", "Weekly Report", "Ops").unwrap();
        assert!(sz_d > 100 && std::fs::read(&docx).unwrap().starts_with(b"PK"));

        let (xlsx, sz_x) = generate_agent_document(dir.path(), "act_x1", "xlsx", "Q4 Tracker", "Tasks").unwrap();
        assert!(sz_x > 100 && std::fs::read(&xlsx).unwrap().starts_with(b"PK"));

        let (csv, sz_c) = generate_agent_document(dir.path(), "act_c1", "csv", "Export Data", "Rows").unwrap();
        assert!(sz_c > 20 && std::fs::read_to_string(&csv).unwrap().contains("Overview"));
    }
}
